NONE_RESOURCE = 'none'

ASLevels = {
    INFO = '^2[asset-deployer:info]^7',
    WARN = '^3[asset-deployer:warn]^7',
    ERROR = '^1[asset-deployer:error]^7',
    LOAD = '^3[asset-deployer:load]^7',
}

function tprint(table)
    return print(json.encode(table, { indent = true }))
end

function afprint(message, prefix, ...)
    print(string.format('%s %s', prefix, message:format(...)))
end

function append(base, ...)
    return base .. table.concat({ ... }, '\n')
end

function appendQB(file, contentToAppend)
    file = file:strtrim()

    return file:gsub('QBShared.Items = {', function(base)
        return base .. '\n' .. contentToAppend .. "\n"
    end)
end


function appendAfterReturn(file, contentToAppend)
    file = file:strtrim()

    return file:gsub('return {', function(base)
        return base .. '\n' .. contentToAppend .. "\n"
    end)
end

function appendAfterJobs(file, contentToAppend)
    file = file:strtrim()

    return file:gsub('QBShared.Jobs = {', function(base)
        return base .. '\n' .. contentToAppend .. "\n"
    end)
end

function isResourceLoaded(resource)
    if resource == NONE_RESOURCE then return true end
    local state = GetResourceState(resource)
    return state == 'started' or state == 'starting'
end

function loadFile(resource, path)
    return LoadResourceFile(resource, path)
end

function table.size(list)
    if not list then
        return 0
    end

    local size = 0

    for _, _ in pairs(list) do
        size = size + 1
    end
    
    return size
end

function resolveDeploy(resource, deploys)
    if not isResourceLoaded(resource) then
        afprint('^1[%s]^7 Resource is not loaded.', ASLevels.ERROR, resource)
        return
    end

    afprint('^3[%s]^7 Deploying resource...', ASLevels.LOAD, resource)

    for id, deploy in pairs(deploys) do
        afprint('^3[%s:%s]^7 Processing...', ASLevels.LOAD, resource, id)
        if deploy.type == 'file' then
            local fileContent = loadFile(resource, deploy.path)

            if not fileContent then
                return dbg.critical("Failed to load content file of resource: %s at path: %s", resource, deploy.path)
            end

            local save = deploy.callback(fileContent, deploy.callbackData)

            if save then
                SaveResourceFile(resource, deploy.path, save, -1)
                afprint('^2[%s:%s]^7 Successfully saved to %s.', ASLevels.INFO, resource, id, deploy.path)
            else
                -- afprint('^1[%s:%s]^7 Deploy was not successful.', ASLevels.ERROR, resource, id)
            end
        elseif deploy.type == 'basic' then
            local status, result = deploy.callback(deploy.callbackData)

            if id == 'Jobs' or id == 'Society' then
                goto Skip
            end

            if not status then
                afprint('^1[%s:%s]^7 Deploy was not successful: %s', ASLevels.ERROR, resource, id, result)
            end

            ::Skip::
        elseif deploy.type == 'copy-files' then
            local source = deploy.source
            local target = deploy.target
            local files = deploy.callback(deploy.callbackData)
            local sourceResourcePath = GetResourcePath(GetCurrentResourceName())
            local resourcePath = GetResourcePath(resource)
            for _, file in ipairs(files) do
                local sourcePath = string.format('%s/%s/%s', sourceResourcePath, source, file)
                local sourceFile = io.open(sourcePath, 'rb')
                if sourceFile == nil then
                    afprint('^1[%s:%s]^7 Source file %s/%s does not exist in resource %s.', ASLevels.ERROR, resource, id,
                        source, file, GetCurrentResourceName())
                    goto continue
                end

                local sourceContent = sourceFile:read('*a')
                sourceFile:close()

                local targetPath = string.format('%s/%s/%s', resourcePath, target, file)
                local targetFile = io.open(targetPath, 'wb')
                if targetFile == nil then
                    afprint('^1[%s:%s]^7 Target file %s/%s does not exist in resource %s.', ASLevels.ERROR, resource, id,
                        target, file, resource)
                    goto continue
                end

                targetFile:write(sourceContent)
                targetFile:close()
                afprint('^2[%s:%s]^7 Successfully copied %s from %s to %s.', ASLevels.INFO, resource, id, file,
                    string.format('%s/%s/', GetCurrentResourceName(), source),
                    string.format('%s/%s/', resource, target))

                :: continue ::
            end
        end
        afprint('^2[%s:%s]^7 Successfully processed.', ASLevels.INFO, resource, id)
    end

    afprint('^2[%s]^7 Successfully deployed resource.', ASLevels.INFO, resource)

    return true
end

function createDeployer()
    local self = {
        deploys = {},
        deploysCache = {},
        command = nil,
        resetDeployCommand = nil,
        saveDeployInCache = false
    }

    function self:registerFileDeploy(id, resource, path, callback, callbackData)
        if not self.deploys[resource] then
            self.deploys[resource] = {}
        end

        self.deploys[resource][id] = {
            type = 'file',
            path = path,
            callback = callback,
            callbackData = callbackData or {}
        }
    end

    function self:registerDeploy(id, resource, callback, callbackData)
        if not self.deploys[resource] then
            self.deploys[resource] = {}
        end

        self.deploys[resource][id] = {
            type = 'basic',
            callback = callback,
            callbackData = callbackData or {}
        }
    end

    function self:registerCopyFilesDeploy(id, resource, source, target, callback, callbackData)
        if not self.deploys[resource] then
            self.deploys[resource] = {}
        end

        self.deploys[resource][id] = {
            type = 'copy-files',
            source = source,
            target = target,
            callback = callback,
            callbackData = callbackData or {}
        }
    end

    function self:deployResourceSpecific(resource, name)
        if self.saveDeployInCache then
            local state = self:getDeployStateForResource(resource)

            if state then
                return afprint('^1[%s]^7 Resource is already deployed.', ASLevels.ERROR, resource)
            end
        end


        return resolveDeploy(resource, { [name] = self.deploys[resource][name] })
    end

    function self:deployResource(resource)
        if self.saveDeployInCache then
            local state = self:getDeployStateForResource(resource)

            if state then
                return afprint('^1[%s]^7 Resource is already deployed.', ASLevels.ERROR, resource)
            end
        end


        return resolveDeploy(resource, self.deploys[resource])
    end

    function self:getDeployCacheNamePrefix(resource)
        return resource and ('%s_%s_%s'):format(GetCurrentResourceName(), 'deployer', resource)
    end

    function self:getDeployStateForResource(resource)
        local retval = false

        if resource then
            local int = GetResourceKvpInt(self:getDeployCacheNamePrefix(resource))

            if int == 1 then
                retval = true
            end
        end

        return retval
    end

    function self:setDeployStateIntoCache(resource, state, skipNotify)
        local key = self:getDeployCacheNamePrefix(resource)

        if key then
            SetResourceKvpInt(key, state)
        end

        if skipNotify then
            return
        end

        if state == 1 then
            afprint('Resource ^3%s^7 deploy was successfully cached into KVP.', ASLevels.INFO, resource)
        elseif state == 0 then
            afprint('Resource ^3%s^7 deploy was succesfully restarted, could be deployed again via command: (/%s %s)',
                ASLevels.LOAD, resource, self.command, resource)
        end
    end

    function self:deleteKVPByResourceName(resource)
        local key = self:getDeployCacheNamePrefix(resource)

        if key then
            SetResourceKvpInt(key, 0)
        end
    end

    function self:getDeployCache(clear)
        local p = promise.new()

        if next(self.deploys) then
            local size = table.len(self.deploys)
            local currentIterate = 0

            for resource, data in pairs(self.deploys) do
                currentIterate = currentIterate + 1

                if resource then
                    local state = self:getDeployStateForResource(resource)

                    if state then
                        self.deploysCache[resource] = {
                            state = state,
                            kvpKey = self:getDeployCacheNamePrefix(resource)
                        }
                    end
                end

                if currentIterate >= size then
                    p:resolve(true)
                end
            end
        else
            p:resolve(true)
        end

        Citizen.Await(p)

        if self.deploysCache and next(self.deploysCache) then
            afprint(
                'Showing current cached resources into KVP storage!',
                ASLevels.LOAD)
            tprint(self.deploysCache)

            if clear then
                local clearIterateCount = 0
                local deployCacheSize = table.len(self.deploysCache)
                local clearPromise = promise.new()
                local clearCache = {}

                for resourceName, v in pairs(self.deploysCache) do
                    if not clearCache[resourceName] then
                        clearCache[resourceName] = {
                            state = 'WAS_REMOVED_FROM_KVP'
                        }
                    end

                    local state = self:getDeployStateForResource(resourceName)

                    if state then
                        self:setDeployStateIntoCache(resourceName, 0, true)
                    end

                    clearIterateCount = clearIterateCount + 1

                    if clearIterateCount >= deployCacheSize then
                        clearPromise:resolve(true)
                    end
                end

                Citizen.Await(clearPromise)

                afprint(
                    'You cleared KVP storage of deployer for current deploys:',
                    ASLevels.LOAD)
                tprint(clearCache)
            end
        else
            afprint(
                'The deployer KVP storage is empty!',
                ASLevels.INFO)
        end
    end

    function self:setSaveDeployInCache(state)
        self.saveDeployInCache = state

        if state then
            afprint(
                'Enabling resource deployer saving deploys into KVP storage.',
                ASLevels.LOAD)
        end
    end

    function self:registerResetDeployCommand(name)
        self.resetDeployCommand = name or 'resetdeploy'

        RegisterCommand(name or 'resetdeploy', function(source, args)
            if source ~= 0 then return end

            if args[1] == nil then
                afprint('Usage: /resetdeploy <resource> [name]', ASLevels.ERROR)
                return
            end

            local resource = args[1]

            if not self.deploys[resource] then
                afprint('Resource %s is not registered yet.', ASLevels.ERROR, resource)
                return
            end

            local state = self:getDeployStateForResource(resource)

            if not state then
                afprint('Resource %s is not stored in KVP storage!', ASLevels.ERROR, resource)
                return
            end

            self:setDeployStateIntoCache(resource, 0)
        end)
    end

    function self:registerDefaultCommand(name)
        self.command = name or 'bannersetup'
        self.deployState = false

        RegisterCommand(name or 'bannersetup', function(source, args)
            if source ~= 0 then return end

            if args[1] == nil then
                afprint('Usage: /bannersetup <resource> [name]', ASLevels.ERROR)
                return
            end

            local resource = args[1]

            if not self.deploys[resource] then
                afprint('Resource %s is not registered yet.', ASLevels.ERROR, resource)
                return
            end

            local name = args[2]

            if name ~= nil then
                if not self.deploys[resource][name] then
                    afprint('Deploy %s is not registered yet.', ASLevels.ERROR, name)
                    return
                end

                self.deployState = self:deployResourceSpecific(resource, name)
                return
            end

            self.deployState = self:deployResource(resource)

            if self.deployState and self.saveDeployInCache then
                self:setDeployStateIntoCache(resource, 1)
            end
        end)
    end

    function self:suggestDeploys(log)
        local suggest = {}
        local suggestKvp = {}

        for resource, deploy in pairs(self.deploys) do
            if isResourceLoaded(resource) then
                suggest[resource] = {}
                suggestKvp[resource] = {}
                
                for id, _ in pairs(deploy) do
                    table.insert(suggest[resource], id)

                    if self.saveDeployInCache then
                        local state = self:getDeployStateForResource(resource)

                        if state then
                            table.insert(suggestKvp[resource], id)
                        end
                    end
                end
            end
        end

        if log then
            for resource, suggested in pairs(suggest) do
                local suggestString = table.concat(suggested, '^7,^3 ')

                if self.saveDeployInCache then
                    local state = self:getDeployStateForResource(resource)

                    if state then
                        afprint(
                            'Resource ^3%s^7 is already deployed. Deploy reset command ^3%s^7: ^3%s^7 (/%s %s)',
                            ASLevels.LOAD, resource, table.size(suggested), suggestString, self.resetDeployCommand,
                            resource)
                    else
                        afprint(
                            'Resource ^3%s^7 is present on server. Suggested ^3%s^7 deploys: ^3%s^7 (/%s %s)',
                            ASLevels.LOAD, resource, table.size(suggested), suggestString, self.command, resource)
                    end
                else
                    afprint(
                        'Resource ^3%s^7 is present on server. Suggested ^3%s^7 deploys: ^3%s^7 (/%s %s)',
                        ASLevels.LOAD, resource, table.size(suggested), suggestString, self.command, resource)
                end
            end
        end

        return suggest
    end

    return self
end

exports('createDeployer', createDeployer)